// @vitest-environment happy-dom
import { describe, expect, it } from "vitest";

import { parseRuntimeConfig } from "@/runtime/config-guard";

/**
 * The runtime's version pin.
 *
 * The runtime must load the exact version its snippet names. Silently
 * accepting a different one would mean a configuration nobody deployed started
 * executing on a live website — which, in an MVP where anyone can generate a
 * configuration, is the whole risk.
 */

function snippet(attributes: Record<string, string>): HTMLScriptElement {
  const script = document.createElement("script");
  for (const [key, value] of Object.entries(attributes)) script.setAttribute(key, value);
  return script;
}

/** Mirrors `readPinnedVersion` in the runtime entry point. */
function readPinnedVersion(script: HTMLScriptElement): number | null {
  const raw = script.dataset.wmfConfig;
  if (!raw || !/^\d{1,7}$/.test(raw)) return null;
  const version = Number(raw);
  return version >= 1 ? version : null;
}

describe("reading the pinned version", () => {
  it("reads a valid version", () => {
    expect(readPinnedVersion(snippet({ "data-wmf-config": "4" }))).toBe(4);
    expect(readPinnedVersion(snippet({ "data-wmf-config": "1" }))).toBe(1);
  });

  it("refuses a missing attribute rather than defaulting to latest", () => {
    expect(readPinnedVersion(snippet({ "data-wmf-site": "wmf_X" }))).toBeNull();
  });

  it("refuses values that are not a positive integer version", () => {
    for (const raw of ["", "0", "-1", "latest", "4.5", "v4", " 4", "99999999", "1e3"]) {
      expect(readPinnedVersion(snippet({ "data-wmf-config": raw })), raw).toBeNull();
    }
  });
});

describe("config payload guard", () => {
  const valid = {
    schemaVersion: 1,
    siteId: "wmf_0123456789ABCDEFGHJKMNPQ",
    configVersion: 4,
    origin: "https://portfolio.example",
    enabledCapabilities: ["list_projects"],
    mapping: {
      version: 1,
      projects: {
        route: "/",
        itemSelector: ".project-card",
        fields: { title: { selector: "h3", source: "text" } },
      },
    },
    generatedAt: "2026-09-03T00:00:00.000Z",
  };

  it("accepts a well-formed payload and preserves its version", () => {
    const parsed = parseRuntimeConfig(valid);
    expect(parsed?.configVersion).toBe(4);
    expect(parsed?.origin).toBe("https://portfolio.example");
  });

  it("rejects a payload that is not structurally sound", () => {
    expect(parseRuntimeConfig({ ...valid, schemaVersion: 2 })).toBeNull();
    expect(parseRuntimeConfig({ ...valid, siteId: "" })).toBeNull();
    expect(parseRuntimeConfig({ ...valid, origin: "" })).toBeNull();
    expect(parseRuntimeConfig(null)).toBeNull();
  });

  it("carries the origin the runtime binds against", () => {
    // The runtime refuses to register tools unless this equals the page's own
    // origin, so a copied snippet cannot activate elsewhere.
    const parsed = parseRuntimeConfig(valid);
    expect(parsed?.origin).not.toBe("https://attacker.example");
  });
});

describe("version mismatch handling", () => {
  /** Mirrors the runtime's guard after fetching. */
  const accepts = (pinned: number, received: number) => pinned === received;

  it("accepts only an exact match", () => {
    expect(accepts(4, 4)).toBe(true);
    // A newer version generated by someone else must not run here.
    expect(accepts(2, 3)).toBe(false);
    expect(accepts(4, 1)).toBe(false);
  });
});
